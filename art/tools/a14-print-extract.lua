-- A14: A13's hand-drawn tee prints, taken from art/character/sells.aseprite (A13's concept: frame 1 the back,
-- frame 2 the front) as rows relative to the shirt's anchor (its centre column and its top at that column), and
-- written to art/tools/a14-print.lua for a14-build.lua to stamp into every frame. Run once, before A14's build
-- overwrites sells.aseprite: Aseprite -b --script "C:/Hogg Squash/hogg-squash/art/tools/a14-print-extract.lua"

local L = dofile("C:/Hogg Squash/hogg-squash/art/tools/pixel-lib.lua")
local A = dofile("C:/Hogg Squash/hogg-squash/art/tools/a14-lib.lua")
local R = L.ROOT
local pal = L.loadPalette(R .. "art/palette/hogg-squash.gpl")
local I = function(n) return L.paletteIndex(pal, n) end
local S = A.indices(pal)

local spr = app.open(R .. "art/character/sells.aseprite")
local function grid(frame)
  local cel = spr.layers[1]:cel(frame)
  local q = { w = spr.width, h = spr.height, px = {} }
  for y = 0, q.h - 1 do
    q.px[y] = {}
    for x = 0, q.w - 1 do q.px[y][x] = 0 end
  end
  for it in cel.image:pixels() do
    local c = it()
    if c ~= 0 then q.px[it.y + cel.position.y][it.x + cel.position.x] = c end
  end
  return q
end

-- The print's box around the anchor (x from cx + x0 to cx + x1, y from top + y0 to top + y1), from A13's clear
-- areas: back { 23, 19, 45, 34 }, front { 24, 21, 42, 36 } on its grid.
local BOX = { back = { -12, 2, 12, 19 }, front = { -10, 4, 10, 21 } }
local out = { "-- Generated by a14-print-extract.lua from A13's sells.aseprite. Each view: the box relative to the anchor,",
  "-- and rows of palette names by key ('.' = plain shirt, ' ' = leave as it is).", "return {" }
for f, view in ipairs({ "back", "front" }) do
  local q = grid(f)
  local cx, top = A.anchor(q, S)
  local b = BOX[view]
  print(string.format("%s: anchor %d, %d", view, cx, top))
  local keys, names, rows = {}, {}, {}
  local nextKey = string.byte("a")
  for y = top + b[2], top + b[4] do
    local row = {}
    for x = cx + b[1], cx + b[3] do
      local c = q.px[y][x]
      local k
      if S.shirt[c] then k = "."
      elseif c == 0 or S.skinHair[c] then k = " "
      else
        local n = pal[c][4]
        if not keys[n] then
          keys[n] = string.char(nextKey); nextKey = nextKey + 1
          names[#names + 1] = string.format("%s = %q", keys[n], n)
        end
        k = keys[n]
      end
      row[#row + 1] = k
    end
    rows[#rows + 1] = string.format("      %q,", table.concat(row))
    print("  " .. table.concat(row))
  end
  out[#out + 1] = string.format("  %s = {\n    box = { %d, %d, %d, %d },\n    key = { %s },\n    rows = {", view,
    b[1], b[2], b[3], b[4], table.concat(names, ", "))
  for _, r in ipairs(rows) do out[#out + 1] = r end
  out[#out + 1] = "    },\n  },"
end
out[#out + 1] = "}"
spr:close()
local fh = io.open(R .. "art/tools/a14-print.lua", "w")
fh:write(table.concat(out, "\n") .. "\n")
fh:close()
print("wrote art/tools/a14-print.lua")
